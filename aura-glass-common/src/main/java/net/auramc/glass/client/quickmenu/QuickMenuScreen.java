    private void nativeClip() {















        double scale = client.getWindow().getScaleFactor();















        int left = (int) Math.ceil(clipLeft * scale), right = (int) Math.floor(clipRight * scale);















        int top = (int) Math.ceil(clipTop * scale), bottom = (int) Math.floor(clipBottom * scale);















        org.lwjgl.opengl.GL33C.glEnable(org.lwjgl.opengl.GL33C.GL_SCISSOR_TEST);















        org.lwjgl.opengl.GL33C.glScissor(left, client.getWindow().getFramebufferHeight() - bottom, Math.max(0, right - left), Math.max(0, bottom - top));















    }































    private void flushNative() {















        nativeClip();















        AuraRenderer.flush();















    }































    // Pure alpha mask fading without dark background rectangles















    private float edgeFade(float itemY, float itemH) {















        if (clipBottom <= clipTop) return 1.0f;















        if (itemY + itemH <= clipTop || itemY >= clipBottom) return 0.0f;















        float topFade = scroll <= 0 ? 1.0f : Math.min(1.0f, Math.max(0.0f, (itemY - clipTop) / 16.0f));















        float bottomFade = Math.min(1.0f, Math.max(0.0f, (clipBottom - (itemY + Math.min(20.0f, itemH))) / 16.0f));















        return Math.max(0.0f, Math.min(1.0f, Math.min(topFade, bottomFade)));















    }































        private static List<String> wrapText(String text, float maxWidth, float size, int weight) {



        List<String> lines = new ArrayList<>();



        if (text == null || text.isEmpty()) return lines;



        if (AuraRenderer.textWidth(text, size, weight) <= maxWidth) {



            lines.add(text);



            return lines;



        }



        String[] words = text.split(" ");



        StringBuilder current = new StringBuilder();



        for (String w : words) {



            String test = current.length() == 0 ? w : current + " " + w;



            if (AuraRenderer.textWidth(test, size, weight) <= maxWidth) {



                current.setLength(0);



                current.append(test);



            } else {



                if (current.length() > 0) {



                    lines.add(current.toString());



                    current.setLength(0);



                    current.append(w);



                } else {



                    lines.add(w);



                }



            }



        }



        if (current.length() > 0) {



            lines.add(current.toString());



        }



        return lines;



    }







    private int maxScroll(float viewportH) {

        float fbH = client != null && client.getWindow() != null ? (float) client.getWindow().getFramebufferHeight() : height;

        float k = fbH / 1080.0f;

        double scale = client != null && client.getWindow() != null ? client.getWindow().getScaleFactor() : 1.0;

        float s = (float) (k / scale);

        return maxScroll(viewportH, 0, s);

    }



    private int maxScroll(float viewportH, float contentW, float s) {



        float contentH;



        if (section == 0) {



            contentH = 1750 * s;



        } else if (section == 1) {



            contentH = 220 * s;



        } else if (section == 2) {



            var src = MusicSourceProvider.get();



            if (!src.available()) {



                contentH = 80 * s;



            } else {



                float header = 314 * s;



                var snap = musicController.snapshot();



                int listCount = snap.countForTab(musicTab);



                float tabContent = (musicTab == 1 ? 48 * s : 0) + Math.min(10, listCount) * 48 * s;



                float karaoke = 32 * s + (karaokeExpanded ? 5 * 48 * s + 12 * s : 0);



                contentH = header + tabContent + karaoke + 24 * s;



            }



        } else {



            contentH = 80 * s;



        }



        return (int) Math.max(0, contentH - viewportH);



    }







